"""The course glossary, generated from every passage's gloss table (docs/content-spec.md, 9).

One entry per distinct (term, gloss); "first seen" is the earliest passage in
course order. The app shows it at /glossary; tools/build_glossary.py writes it
to content/glossary.md for readers of the Markdown.
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field

from .model import Course, Passage


@dataclass
class Entry:
    term: str
    pinyin: str
    gloss: str                       # Markdown, as in the gloss table
    grammar: str
    first: Passage
    passages: list[Passage] = field(default_factory=list)

    @property
    def sort_key(self) -> tuple:
        return (plain_pinyin(self.pinyin), self.pinyin, self.term)


def plain_pinyin(s: str) -> str:
    """Lower-case pinyin without tone marks or punctuation, for sorting and searching."""
    s = unicodedata.normalize("NFD", s.lower())
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.replace("ü", "v").replace("u\u0308", "v")
    return re.sub(r"[^a-zv …]", "", s).strip()


def passages_in_order(course: Course) -> list[Passage]:
    out = []
    for uid in course.unit_order():
        out.extend(course.passages[p] for p in course.units[uid].passage_ids)
    listed = {p.id for p in out}
    out.extend(p for pid, p in sorted(course.passages.items()) if pid not in listed)
    return out


def build(course: Course) -> list[Entry]:
    entries: dict[tuple[str, str], Entry] = {}
    for p in passages_in_order(course):
        for gl in p.glosses:
            key = (gl.term, " ".join(gl.gloss.split()))
            e = entries.get(key)
            if e is None:
                entries[key] = e = Entry(gl.term, gl.pinyin, gl.gloss, gl.grammar, p)
            if not e.grammar and gl.grammar:
                e.grammar = gl.grammar
            if p not in e.passages:
                e.passages.append(p)
    return sorted(entries.values(), key=lambda e: e.sort_key)


def initial(e: Entry) -> str:
    """The letter an entry is filed under."""
    s = plain_pinyin(e.pinyin)
    return s[0].upper() if s and s[0].isalpha() else "#"


def to_markdown(course: Course, entries: list[Entry]) -> str:
    def cell(s: str) -> str:
        return s.replace("|", "\\|").replace("\n", " ")

    lines = [
        "<!-- Generated by tools/build_glossary.py from the passage gloss tables. Do not edit by hand. -->",
        "",
        "| Term | Pinyin | Gloss | First seen | Grammar |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        lines.append(f"| {cell(e.term)} | {cell(e.pinyin)} | {cell(e.gloss)} | {e.first.id} | {e.grammar} |")
    return "\n".join(lines) + "\n"
